export function drawSpread(count = 3) {
  const pool = [...FULL_DECK];
  for (let m = pool.length - 1; m > 0; m--) {
    const i = Math.floor(Math.random() * (m + 1));
    [pool[m], pool[i]] = [pool[i], pool[m]];
  }
  return pool.slice(0, count).map(card => ({
    ...card,
    isUpright: Math.random() < 0.5
  }));
}
